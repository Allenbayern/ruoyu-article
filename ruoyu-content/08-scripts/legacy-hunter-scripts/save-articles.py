# Save each article as MD  
meta = {
    "date": datetime.now().strftime("%Y-%m-%d"),
    "fetched_at": datetime.now().isoformat(),
    "total": len(articles),
    "articles": [],
}

for i, a in enumerate(articles):
    safe_title = re.sub(r'[\\/:*?"<>|]', '_', a['title'][:40])
    fname = f"{i+1:02d}-{safe_title}.md"
    fpath = os.path.join(DIR, fname)

    md = f"# {a['title']}\n\n"
    md += f"- **来源**: {a['source']}\n"
    md += f"- **链接**: {a['url']}\n"
    md += f"- **字数**: {a['word_count']}\n"
    md += f"- **类型**: {a['type']}\n\n"
    md += "---\n\n## 正文\n\n"
    md += a['content'] + "\n\n---\n\n"
    md += "## 🧬 进化小组分析区\n\n"
    md += "### 🔥 热点猎手\n- 传播路径:\n- 情绪触发点:\n- 信息源追溯:\n\n"
    md += "### 📋 选题策划\n- 选题角度:\n- 标题公式:\n- 分享动机:\n\n"
    md += "### ✍️ 封不住\n- 开头钩子类型:\n- 叙事结构:\n- 金句摘录:\n- 可复用技巧:\n"

    with open(fpath, 'w', encoding='utf-8') as f:
        f.write(md)

    meta["articles"].append({
        "title": a['title'], "source": a['source'],
        "word_count": a['word_count'], "file": fname
    })

# Save metadata
with open(os.path.join(DIR, "metadata.json"), 'w') as f:
    json.dump(meta, f, ensure_ascii=False, indent=2)

print(f"\n💾 已保存 {len(articles)} 篇 → {DIR}/")
total_words = sum(a['word_count'] for a in articles)
print(f"   总字数: {total_words}")
for a in articles:
    print(f"   📄 [{a['type']}] {a['title'][:45]}... ({a['word_count']}字)")
